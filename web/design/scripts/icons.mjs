const require = createRequire(import.meta.url);
const pkg = require.resolve('lucide-static/package.json');
const { version } = JSON.parse(readFileSync(pkg, 'utf8'));
const nodes = JSON.parse(readFileSync(new URL('icon-nodes.json', `file://${pkg}`), 'utf8'));

const n = (v) => Number(v ?? 0);

const NUMBER = /^\s*,?\s*(-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?)/i;

/**
 * A path's data made absolute at its start: lucide often opens with a relative `m`, which is
 * relative to the origin on its own but to the last point once joined after another element.
 */
function absoluteStart (d) {
  const m = d.trimStart();
  if (m[0] !== 'm') return m;
  let rest = m.slice(1);
  const xy = [];
  for (let k = 0; k < 2; k++) {
    const [token, value] = rest.match(NUMBER);
    xy.push(value);
    rest = rest.slice(token.length);
  }
  // Pairs after a moveto are its linetos, relative ones after `m`.
  return `M${xy[0]} ${xy[1]}${NUMBER.test(rest) ? `l${rest.trimStart().replace(/^,/, '')}` : rest}`;
}

/** One lucide element as path data, so a renderer needs only one <path>. */
function toPath ([tag, a]) {
  switch (tag) {
    case 'path': return absoluteStart(a.d);
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle':
    case 'ellipse': {
      const cx = n(a.cx); const cy = n(a.cy);
      const rx = n(a.rx ?? a.r); const ry = n(a.ry ?? a.r);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case 'rect': {
      const x = n(a.x); const y = n(a.y); const w = n(a.width); const h = n(a.height);
      const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}`
        + `h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    default: throw new Error(`lucide element <${tag}> has no path form`);
  }
}

const entries = Object.entries(ICONS).map(([name, lucide]) => {
  const icon = nodes[lucide];
  if (!icon) throw new Error(`lucide has no icon '${lucide}' (for '${name}')`);
  return [name, icon.map(toPath).join('')];
});

const header = `// Generated by scripts/icons.mjs from lucide-static ${version} (ISC). Do not edit.\n`;
const files = new Map();
files.set('icons.js', `${header}
/** anfra's icons, by name: path data on a 24px grid, drawn with a 2px round stroke and no fill. */
export const ICONS = {
${entries.map(([name, d]) => `  ${JSON.stringify(name)}: ${JSON.stringify(d)},`).join('\n')}
};
`);
files.set('icons.d.ts', `${header}
export type IconName =
${entries.map(([name]) => `  | ${JSON.stringify(name)}`).join('\n')};

/** anfra's icons, by name: path data on a 24px grid, drawn with a 2px round stroke and no fill. */
export declare const ICONS: Readonly<Record<IconName, string>>;
`);
for (const [file, text] of files) {
  const url = new URL(`../${file}`, import.meta.url);
  if (!process.argv.includes('--check')) writeFileSync(url, text);
  else if (readFileSync(url, 'utf8') !== text) throw new Error(`${file} is stale: run scripts/icons.mjs`);
}
console.log(`${entries.length} icons from lucide-static ${version}`);
